/* =====================================================
   ENTER / ARROW KEYS
===================================================== */

searchInput.addEventListener(
    "keydown",
    function (event) {

        const items =
            suggestionsBox.querySelectorAll(
                ".suggestion"
            );


        /* Arrow Down */

        if (
            event.key === "ArrowDown" &&
            items.length
        ) {

            event.preventDefault();


            selectedSuggestion++;


            if (
                selectedSuggestion >=
                items.length
            ) {

                selectedSuggestion = 0;

            }


            updateActiveSuggestion();

        }


        /* Arrow Up */

        else if (
            event.key === "ArrowUp" &&
            items.length
        ) {

            event.preventDefault();


            selectedSuggestion--;


            if (
                selectedSuggestion < 0
            ) {

                selectedSuggestion =
                    items.length - 1;

            }


            updateActiveSuggestion();

        }


        /* Enter */

        else if (
            event.key === "Enter"
        ) {

            event.preventDefault();


            if (
                selectedSuggestion >= 0 &&
                items[selectedSuggestion]
            ) {

                items[
                    selectedSuggestion
                ].click();

            }

            else {

                performSearch(
                    searchInput.value
                );

            }

        }


        /* Escape */

        else if (
            event.key === "Escape"
        ) {

            suggestionsBox.style.display =
                "none";

        }

    }
);


